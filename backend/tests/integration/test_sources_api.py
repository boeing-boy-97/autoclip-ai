"""Source-upload integration tests.

These exercise the real pipeline end to end: multipart upload → magic-byte check → FFmpeg
`ffprobe` inspection of a genuine encoded file → persistence → stage-machine journal.

Every assertion is about observed behaviour of real bytes on disk. Nothing is stubbed: the
fixtures in `tests/fixtures/generated/` are produced by FFmpeg, and their metadata below is
independently verifiable with `ffprobe`.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest

from tests.integration.conftest import Actor

FIXTURES = Path(__file__).resolve().parents[1] / "fixtures" / "generated"
RIGHTS_STATEMENT = "I recorded this footage myself and own all rights to it."

pytestmark = pytest.mark.integration


def fixture(name: str) -> Path:
    path = FIXTURES / name
    if not path.exists():
        pytest.skip(f"media fixture missing: {name} (run ops/scripts/make_fixtures.sh)")
    return path


def upload(
    actor: Actor,
    project_id: str,
    path: Path,
    *,
    filename: str | None = None,
    content_type: str = "video/mp4",
    rights_basis: str = "original",
    rights_statement: str = RIGHTS_STATEMENT,
    csrf: str | None = None,
):
    url = f"/api/v1/workspaces/{actor.workspace_id}/projects/{project_id}/sources"
    headers = {"X-CSRF-Token": csrf} if csrf is not None else actor.headers
    return actor.client.post(
        url,
        files={"file": (filename or path.name, path.read_bytes(), content_type)},
        data={"rights_basis": rights_basis, "rights_statement": rights_statement},
        headers=headers,
    )


class TestSuccessfulUpload:
    def test_real_video_is_probed_and_persisted(self, alice: Actor, db_engine):
        """The recorded facts must match what FFmpeg reports for the fixture.

        talking_30s.mp4 is generated by make_fixtures.sh as 640x360 H.264/AAC, 30 s.
        """
        project = alice.create_project(name="Upload")
        resp = upload(alice, project["id"], fixture("talking_30s.mp4"))
        assert resp.status_code == 201, resp.text

        body = resp.json()
        assert body["state"] == "ready"
        assert body["original_filename"] == "talking_30s.mp4"
        assert body["duration_ms"] == pytest.approx(30_000, abs=100)
        assert body["width"] == 640
        assert body["height"] == 360
        assert body["video_codec"] == "h264"
        assert body["audio_codec"] == "aac"
        assert body["byte_size"] == fixture("talking_30s.mp4").stat().st_size
        # sha256 is a hex string, never raw bytes in JSON.
        assert isinstance(body["sha256"], str)
        assert len(body["sha256"]) == 64
        assert body["rights_basis"] == "original"

        # Row really exists in PostgreSQL (not just in the response).
        from sqlalchemy import text

        with db_engine.connect() as conn:
            row = conn.execute(
                text("SELECT state, duration_ms, storage_key FROM source_videos WHERE id = :id"),
                {"id": body["id"]},
            ).one()
        assert row.state == "ready"
        assert row.duration_ms == pytest.approx(30_000, abs=100)
        assert row.storage_key  # object key recorded

    def test_pipeline_advances_through_real_stages(self, alice: Actor):
        project = alice.create_project()
        assert upload(alice, project["id"], fixture("talking_30s.mp4")).status_code == 201

        detail = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{project['id']}"
        ).json()
        assert detail["status"] == "MEDIA_INSPECTION"
        assert detail["progress"] is not None
        assert detail["source"]["state"] == "ready"
        assert detail["source"]["duration_ms"] == pytest.approx(30_000, abs=100)

        journal = [(e["from_status"], e["to_status"]) for e in detail["stage_events"]]
        assert journal == [
            (None, "CREATED"),
            ("CREATED", "SOURCE_VALIDATION"),
            ("SOURCE_VALIDATION", "INGESTING"),
            ("INGESTING", "MEDIA_INSPECTION"),
        ]

    def test_stored_object_is_readable_and_complete(self, alice: Actor):
        """The bytes at the recorded key must be the uploaded file, byte for byte."""
        project = alice.create_project()
        body = upload(alice, project["id"], fixture("silent.mp4")).json()

        from sqlalchemy import text

        from app.core.config import get_settings
        from app.db.session import get_engine

        with get_engine().connect() as conn:
            key = conn.execute(
                text("SELECT storage_key FROM source_videos WHERE id = :id"), {"id": body["id"]}
            ).scalar_one()
        stored = Path(get_settings().local_storage_root) / key
        assert stored.exists(), f"expected object at {stored}"
        assert stored.read_bytes() == fixture("silent.mp4").read_bytes()


class TestRejections:
    def test_magic_bytes_must_match_extension(self, alice: Actor):
        """Random bytes named .mp4 are refused before FFmpeg is ever invoked."""
        project = alice.create_project()
        resp = upload(alice, project["id"], fixture("corrupt.mp4"))
        # corrupt.mp4 is a real .mp4 header with a broken body: accepted by the signature check,
        # rejected by ffprobe. Both paths must refuse; the message says which stage refused.
        assert resp.status_code == 415, resp.text
        assert resp.json()["code"] in {"unsupported_media", "corrupt_media"}

    def test_renamed_file_is_refused_by_signature(self, alice: Actor, tmp_path: Path):
        fake = tmp_path / "video.mp4"
        fake.write_bytes(b"\x00\x01\x02\x03" * 5000)  # no container signature at all
        project = alice.create_project()
        resp = upload(alice, project["id"], fake, filename="video.mp4")
        assert resp.status_code == 415, resp.text
        assert resp.json()["code"] == "unsupported_media"
        assert "signature" in resp.json()["detail"]

    def test_audio_only_file_is_refused(self, alice: Actor):
        """A WAV has no video stream, so it cannot produce video output."""
        project = alice.create_project()
        resp = upload(alice, project["id"], fixture("speech_10s.wav"), content_type="audio/wav")
        assert resp.status_code == 415, resp.text
        assert resp.json()["code"] == "unsupported_media"  # .wav is not an allowed extension

    def test_rejection_leaves_project_retryable(self, alice: Actor):
        """A refused file must not burn the project — the user can immediately try again."""
        project = alice.create_project()
        bad = upload(alice, project["id"], fixture("corrupt.mp4"))
        assert bad.status_code == 415

        detail = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{project['id']}"
        ).json()
        assert detail["status"] == "CREATED", "project must stay usable after a bad upload"
        assert detail["source"] is None, "no source row may block the retry"

        good = upload(alice, project["id"], fixture("talking_30s.mp4"))
        assert good.status_code == 201, good.text

    def test_rejection_is_audited(self, alice: Actor, db_engine):
        project = alice.create_project()
        upload(alice, project["id"], fixture("corrupt.mp4"))

        from sqlalchemy import text

        with db_engine.connect() as conn:
            rows = conn.execute(
                text(
                    "SELECT action, detail FROM audit_logs "
                    "WHERE action = 'source.rejected' AND target_id = :pid"
                ),
                {"pid": project["id"]},
            ).all()
        assert len(rows) == 1, "a refused upload must leave an audit trail"
        assert "reason" in rows[0].detail

    def test_rights_declaration_is_mandatory(self, alice: Actor):
        """No rights basis means no ingestion. Rejected at the edge (422) either way."""
        project = alice.create_project()
        resp = upload(alice, project["id"], fixture("silent.mp4"), rights_basis="")
        assert resp.status_code == 422, resp.text
        assert resp.json()["code"] in {"source_not_authorized", "validation_error"}

    def test_short_rights_statement_is_rejected(self, alice: Actor):
        project = alice.create_project()
        resp = upload(alice, project["id"], fixture("silent.mp4"), rights_statement="mine")
        assert resp.status_code == 422, resp.text
        assert resp.json()["code"] == "source_not_authorized"

    def test_unknown_rights_basis_is_rejected(self, alice: Actor):
        project = alice.create_project()
        resp = upload(alice, project["id"], fixture("silent.mp4"), rights_basis="whatever")
        assert resp.status_code == 422, resp.text

    def test_wrong_extension_is_rejected(self, alice: Actor, tmp_path: Path):
        copy = tmp_path / "clip.txt"
        shutil.copyfile(fixture("silent.mp4"), copy)
        project = alice.create_project()
        resp = upload(alice, project["id"], copy, filename="clip.txt")
        assert resp.status_code == 415, resp.text
        assert "extension" in resp.json()["detail"]

    def test_upload_without_csrf_is_forbidden(self, alice: Actor):
        project = alice.create_project()
        resp = upload(alice, project["id"], fixture("silent.mp4"), csrf="not-a-token")
        assert resp.status_code == 403, resp.text
        assert resp.json()["code"] == "forbidden"


class TestAuthorization:
    def test_non_member_cannot_upload(self, alice: Actor, bob: Actor):
        """Bob targets Alice's workspace directly: refused at the workspace boundary."""
        project = alice.create_project()
        resp = bob.client.post(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{project['id']}/sources",
            files={"file": ("a.mp4", fixture("silent.mp4").read_bytes(), "video/mp4")},
            data={"rights_basis": "original", "rights_statement": RIGHTS_STATEMENT},
            headers=bob.headers,
        )
        assert resp.status_code == 404, resp.text
        assert resp.json()["code"] == "workspace_not_found"

    def test_foreign_project_id_under_own_workspace_is_404(self, alice: Actor, bob: Actor):
        """Bob uses his own workspace but Alice's project id: no data leaks either way."""
        project = alice.create_project()
        resp = upload(bob, project["id"], fixture("silent.mp4"))
        assert resp.status_code == 404, resp.text
        assert resp.json()["code"] == "project_not_found"

    def test_unauthenticated_upload_is_401(self, alice: Actor):
        from fastapi.testclient import TestClient

        from app.main import create_app

        project = alice.create_project()
        with TestClient(create_app(), raise_server_exceptions=False) as anon:
            resp = anon.post(
                f"/api/v1/workspaces/{alice.workspace_id}/projects/{project['id']}/sources",
                files={"file": ("a.mp4", b"x", "video/mp4")},
                data={"rights_basis": "original", "rights_statement": RIGHTS_STATEMENT},
            )
        assert resp.status_code == 401

    def test_second_source_on_same_project_conflicts(self, alice: Actor):
        """A project holds exactly one source; the schema and service agree on that."""
        project = alice.create_project()
        assert upload(alice, project["id"], fixture("silent.mp4")).status_code == 201
        resp = upload(alice, project["id"], fixture("talking_30s.mp4"))
        assert resp.status_code == 409, resp.text
        assert resp.json()["code"] == "project_already_has_source"

    def test_upload_after_analysis_started_conflicts(self, alice: Actor):
        """Once the source is ingested the project leaves the intake states."""
        project = alice.create_project()
        assert upload(alice, project["id"], fixture("silent.mp4")).status_code == 201
        # Project is now MEDIA_INSPECTION, so a further upload cannot attach.
        resp = upload(alice, project["id"], fixture("silent.mp4"))
        assert resp.status_code == 409


class TestReads:
    def test_list_projection(self, alice: Actor):
        project = alice.create_project()
        empty = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{project['id']}/sources"
        )
        assert empty.status_code == 200
        assert empty.json() == []

        created = upload(alice, project["id"], fixture("silent.mp4")).json()
        listed = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{project['id']}/sources"
        ).json()
        assert [s["id"] for s in listed] == [created["id"]]

    def test_get_source_by_id(self, alice: Actor):
        project = alice.create_project()
        created = upload(alice, project["id"], fixture("silent.mp4")).json()
        resp = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{project['id']}"
            f"/sources/{created['id']}"
        )
        assert resp.status_code == 200
        assert resp.json()["id"] == created["id"]

    def test_source_under_wrong_project_is_404(self, alice: Actor):
        project = alice.create_project()
        other = alice.create_project(name="Other")
        created = upload(alice, project["id"], fixture("silent.mp4")).json()
        resp = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{other['id']}"
            f"/sources/{created['id']}"
        )
        assert resp.status_code == 404
        assert resp.json()["code"] == "source_not_found"
