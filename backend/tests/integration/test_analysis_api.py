"""Analysis pipeline tests against real PostgreSQL, real FFmpeg and a real ASR engine.

These tests need genuine speech in the source. The fixture `real_speech.mp4` is generated by
`ops/scripts/make_speech_fixture.sh`: real English sentences spoken by a real TTS voice, encoded
into a real MP4. That means the transcript assertions below are checking an actual model's output,
not a stub — which is the only way to know the pipeline works.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from tests.integration.conftest import Actor

MEDIA = Path(__file__).resolve().parents[1] / "fixtures" / "generated"
RIGHTS = "I recorded this footage myself and own all rights to it."
SPEECH = MEDIA / "real_speech.mp4"

pytestmark = pytest.mark.integration


def need_speech() -> Path:
    if not SPEECH.exists():
        pytest.skip("speech fixture missing; run ops/scripts/make_speech_fixture.sh")
    return SPEECH


def upload(actor: Actor, project_id: str, path: Path) -> dict:
    resp = actor.client.post(
        f"/api/v1/workspaces/{actor.workspace_id}/projects/{project_id}/sources",
        files={"file": (path.name, path.read_bytes(), "video/mp4")},
        data={"rights_basis": "original", "rights_statement": RIGHTS},
        headers=actor.headers,
    )
    assert resp.status_code == 201, resp.text
    return resp.json()


def analyse(actor: Actor, project_id: str, **params):
    return actor.client.post(
        f"/api/v1/workspaces/{actor.workspace_id}/projects/{project_id}/analyze",
        headers=actor.headers,
        params=params,
    )


@pytest.fixture
def ready_project(alice: Actor):
    """A project with a real speech video attached, ready for analysis."""
    project = alice.create_project(
        name="Speech Project",
        min_duration_ms=8000,
        max_duration_ms=30000,
        clips_requested=3,
    )
    upload(alice, project["id"], need_speech())
    return project


class TestTranscription:
    def test_real_speech_is_transcribed_accurately(self, alice: Actor, ready_project):
        resp = analyse(alice, ready_project["id"])
        assert resp.status_code == 202, resp.text

        body = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{ready_project['id']}/transcript"
        )
        assert body.status_code == 200
        transcript = body.json()

        assert transcript["provider"] == "faster-whisper"
        assert transcript["language"] == "en"
        assert transcript["segments"], "a speech file must produce segments"
        assert transcript["word_count"] > 40

        # The fixture's script is fixed, so specific words must appear. This is what separates a
        # real transcript from plausible-looking filler.
        full_text = " ".join(s["text"] for s in transcript["segments"]).lower()
        for expected in ("learning to code", "memorizing syntax", "small project"):
            assert expected in full_text, f"expected '{expected}' in transcript: {full_text[:200]}"

    def test_segments_are_ordered_and_within_the_source(self, alice: Actor, ready_project):
        analyse(alice, ready_project["id"])
        transcript = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{ready_project['id']}/transcript"
        ).json()

        starts = [s["start_ms"] for s in transcript["segments"]]
        assert starts == sorted(starts), "segments must be in time order"
        for seg in transcript["segments"]:
            assert 0 <= seg["start_ms"] < seg["end_ms"] <= (transcript["duration_ms"] or 10**9)

    def test_word_timings_are_opt_in(self, alice: Actor, ready_project):
        analyse(alice, ready_project["id"])
        url = f"/api/v1/workspaces/{alice.workspace_id}/projects/{ready_project['id']}/transcript"
        lean = alice.client.get(url).json()
        rich = alice.client.get(url, params={"include_words": True}).json()

        assert all(s["words"] is None for s in lean["segments"])
        assert any(s["words"] for s in rich["segments"]), "include_words must return timings"
        first_word = next(w for s in rich["segments"] if s["words"] for w in s["words"])
        assert set(first_word) >= {"w", "s", "e"}
        assert first_word["e"] >= first_word["s"]

    def test_transcript_persists_to_the_database(self, alice: Actor, ready_project, db_engine):
        analyse(alice, ready_project["id"])
        from sqlalchemy import text

        with db_engine.connect() as conn:
            rows = conn.execute(
                text(
                    "SELECT provider, model, word_timestamps FROM transcripts "
                    "WHERE project_id = :pid"
                ),
                {"pid": ready_project["id"]},
            ).all()
            segments = conn.execute(
                text("SELECT count(*) FROM transcript_segments WHERE project_id = :pid"),
                {"pid": ready_project["id"]},
            ).scalar_one()
        assert len(rows) == 1
        assert rows[0].provider == "faster-whisper"
        assert rows[0].word_timestamps is True
        assert segments > 0


class TestPipelineStages:
    def test_journal_records_every_stage_in_order(self, alice: Actor, ready_project):
        analyse(alice, ready_project["id"])
        detail = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{ready_project['id']}"
        ).json()
        transitions = [(e["from_status"], e["to_status"]) for e in detail["stage_events"]]

        expected_tail = [
            ("MEDIA_INSPECTION", "AUDIO_EXTRACTION"),
            ("AUDIO_EXTRACTION", "TRANSCRIPTION"),
            ("TRANSCRIPTION", "VISUAL_ANALYSIS"),
            ("VISUAL_ANALYSIS", "SEMANTIC_ANALYSIS"),
            ("SEMANTIC_ANALYSIS", "MOMENT_DETECTION"),
        ]
        assert transitions[-5:] == expected_tail
        assert detail["status"] == "MOMENT_DETECTION"

    def test_audio_asset_is_stored(self, alice: Actor, ready_project, db_engine):
        analyse(alice, ready_project["id"])
        from sqlalchemy import text

        with db_engine.connect() as conn:
            row = conn.execute(
                text(
                    "SELECT kind, mime, bytes FROM media_assets "
                    "WHERE project_id = :pid AND kind = 'audio_asr'"
                ),
                {"pid": ready_project["id"]},
            ).one()
        assert row.mime == "audio/wav"
        assert row.bytes > 44  # more than a WAV header

    def test_visual_analysis_records_measured_metrics(self, alice: Actor, ready_project, db_engine):
        analyse(alice, ready_project["id"])
        import json

        from sqlalchemy import text

        with db_engine.connect() as conn:
            payload = conn.execute(
                text(
                    "SELECT payload FROM video_analysis WHERE project_id = :pid "
                    "ORDER BY created_at DESC LIMIT 1"
                ),
                {"pid": ready_project["id"]},
            ).scalar_one()
            scenes = conn.execute(
                text("SELECT count(*) FROM scenes WHERE project_id = :pid"),
                {"pid": ready_project["id"]},
            ).scalar_one()

        payload = payload if isinstance(payload, dict) else json.loads(payload)
        metrics = payload["metrics"]
        assert metrics["scene_count"] >= 1
        assert scenes >= 1
        # Real measurements, not placeholders.
        assert 0 <= metrics["mean_brightness"] <= 255
        assert metrics["mean_sharpness"] is not None


class TestScoring:
    def test_moments_carry_decomposed_scores(self, alice: Actor, ready_project):
        analyse(alice, ready_project["id"])
        page = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{ready_project['id']}/moments"
        ).json()

        assert page["total"] > 0
        assert page["disclaimer"], "the not-a-prediction disclaimer must always be present"
        assert "not predictions" in page["disclaimer"]

        for moment in page["items"]:
            score = moment["score"]
            assert score is not None
            # Ten criteria plus four aggregates, all bounded.
            for key in (
                "hook",
                "content_value",
                "narrative",
                "standalone",
                "audience",
                "emotion",
                "visual_quality",
                "audio_quality",
                "ending_strength",
                "clarity",
                "content_potential",
                "technical_quality",
                "context_completeness",
                "audience_relevance",
                "overall",
            ):
                assert 0 <= score[key] <= 100, f"{key} out of range: {score[key]}"
            assert score["weights_version"]

    def test_overall_matches_the_documented_weights(self, alice: Actor, ready_project):
        """Recompute overall from the criteria and the config weights; it must agree."""
        analyse(alice, ready_project["id"])
        page = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{ready_project['id']}/moments"
        ).json()

        from app.services.scoring import load_scoring_config

        config = load_scoring_config("../config/scoring.yaml")
        moment = page["items"][0]
        score = moment["score"]
        recomputed = sum(score[c] * config.weights[c] for c in config.weights)
        assert recomputed == pytest.approx(score["overall"], abs=0.5), (
            "stored overall must equal the weighted sum of its parts"
        )

    def test_scoring_is_deterministic(self, alice: Actor, ready_project):
        """Same transcript, same weights → identical scores. No randomness anywhere."""
        analyse(alice, ready_project["id"])
        url = f"/api/v1/workspaces/{alice.workspace_id}/projects/{ready_project['id']}/moments"
        first = alice.client.get(url).json()
        second = alice.client.get(url).json()
        assert [m["score"]["overall"] for m in first["items"]] == [
            m["score"]["overall"] for m in second["items"]
        ]

    def test_candidates_are_ranked_and_suppression_is_explained(self, alice: Actor, ready_project):
        analyse(alice, ready_project["id"])
        page = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{ready_project['id']}/moments"
        ).json()
        overalls = [m["score"]["overall"] for m in page["items"]]
        assert overalls == sorted(overalls, reverse=True), "items must come back ranked"
        assert any(m["suppressed_reason"] for m in page["items"]) or page["total"] == 1, (
            "overlapping candidates must record why they lost"
        )

    def test_selection_respects_clips_requested(self, alice: Actor, ready_project):
        analyse(alice, ready_project["id"])
        page = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{ready_project['id']}/moments"
        ).json()
        assert page["selected_count"] <= 3  # clips_requested=3

    def test_rationale_is_human_readable_and_cites_evidence(self, alice: Actor, ready_project):
        analyse(alice, ready_project["id"])
        page = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{ready_project['id']}/moments"
        ).json()
        rationale = page["items"][0]["rationale"]
        assert "Score" in rationale
        assert "heuristic" in rationale


class TestIdempotency:
    def test_repeat_analysis_reuses_work(self, alice: Actor, ready_project, db_engine):
        first = analyse(alice, ready_project["id"]).json()
        second = analyse(alice, ready_project["id"]).json()
        assert first["transcript_id"] == second["transcript_id"]

        from sqlalchemy import text

        with db_engine.connect() as conn:
            transcripts = conn.execute(
                text("SELECT count(*) FROM transcripts WHERE project_id = :pid"),
                {"pid": ready_project["id"]},
            ).scalar_one()
            moments = conn.execute(
                text("SELECT count(*) FROM candidate_moments WHERE project_id = :pid"),
                {"pid": ready_project["id"]},
            ).scalar_one()
        assert transcripts == 1, "a repeat run must not duplicate the transcript"
        assert moments > 0

    def test_force_flag_reruns(self, alice: Actor, ready_project):
        analyse(alice, ready_project["id"])
        forced = analyse(alice, ready_project["id"], force=True)
        assert forced.status_code == 202


class TestHonestFailures:
    def test_silent_source_is_refused_not_fabricated(self, alice: Actor):
        """A video with no speech must fail loudly. Invented segments would be a lie."""
        project = alice.create_project(name="No Speech")
        tones = MEDIA / "talking_30s.mp4"  # a test pattern with a sine tone, no speech
        if not tones.exists():
            pytest.skip("talking_30s.mp4 fixture missing")
        upload(alice, project["id"], tones)

        resp = analyse(alice, project["id"])
        assert resp.status_code == 422, resp.text
        assert resp.json()["code"] == "no_speech_detected"

        status = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{project['id']}/analysis"
        ).json()
        assert status["has_transcript"] is False
        assert status["candidate_count"] == 0

    def test_no_transcript_rows_are_written_on_failure(self, alice: Actor, db_engine):
        project = alice.create_project(name="No Speech 2")
        tones = MEDIA / "talking_30s.mp4"
        if not tones.exists():
            pytest.skip("talking_30s.mp4 fixture missing")
        upload(alice, project["id"], tones)
        analyse(alice, project["id"])

        from sqlalchemy import text

        with db_engine.connect() as conn:
            transcripts = conn.execute(
                text("SELECT count(*) FROM transcripts WHERE project_id = :pid"),
                {"pid": project["id"]},
            ).scalar_one()
            jobs = conn.execute(
                text("SELECT status, error_code FROM processing_jobs WHERE project_id = :pid"),
                {"pid": project["id"]},
            ).all()
        assert transcripts == 0
        assert jobs, "a job row must exist so the failure is discoverable"
        # No speech is not a transient error: the job is FAILED, not dead-lettered for a retry
        # that could only fail again.
        assert jobs[0].status == "FAILED"
        assert jobs[0].error_code == "no_speech_detected"

    def test_analysis_without_a_source_is_409(self, alice: Actor):
        project = alice.create_project(name="Empty")
        resp = analyse(alice, project["id"])
        assert resp.status_code == 409
        assert resp.json()["code"] == "source_not_ready"

    def test_transcript_missing_is_404_with_guidance(self, alice: Actor):
        project = alice.create_project(name="Empty 2")
        resp = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{project['id']}/transcript"
        )
        assert resp.status_code == 404
        assert resp.json()["code"] == "transcript_not_found"
        assert "analyze" in resp.json()["detail"].lower()

    def test_moments_empty_page_is_not_an_error(self, alice: Actor):
        project = alice.create_project(name="Empty 3")
        resp = alice.client.get(
            f"/api/v1/workspaces/{alice.workspace_id}/projects/{project['id']}/moments"
        )
        assert resp.status_code == 200
        assert resp.json()["items"] == []
        assert resp.json()["total"] == 0


